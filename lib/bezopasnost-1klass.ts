function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** Возвращает `count` случайных вопросов без повторов, с перемешанными вариантами ответа. */
export function pickSafetyQuestions1Klass(count: number): SafetyQuestion1Klass[] {
  const shuffled = shuffle(SAFETY_QUESTIONS_1KLASS).slice(0, Math.min(count, SAFETY_QUESTIONS_1KLASS.length));
  return shuffled.map((q) => {
    const correctOption = q.options[q.correct];
    const shuffledOptions = shuffle(q.options);
    return {
      emoji: q.emoji,
      text: q.text,
      options: shuffledOptions,
      correct: shuffledOptions.indexOf(correctOption),
    };
  });
}
