// Организмы, для которых указанный хищник питается не самим производителем напрямую,
// а животным-жертвой (о.food) — цепь строится в 4 звена, иначе получается абсурд вида
// "трава → лиса → хищник" (лиса не ест траву напрямую).
const INDIRECT_CHAIN = new Set(['лягушка', 'ёж', 'морская звезда', 'божья коровка', 'лиса', 'сова']);

// Редуценты — питаются остатками организмов или готовыми органическими веществами,
// а не производителем напрямую и не становятся добычей хищника в обычной цепи питания
// (иначе получается абсурд вида "молоко → бактерия → хищник").
const DECOMPOSERS = new Set(['дождевой червь', 'подберёзовик', 'бактерия молочнокислая']);

function kingdom(o: Organism): string {
  if (o.kind === 'животное') return 'животные';
  if (o.kind === 'растение') return 'растения';
  if (o.kind === 'гриб') return 'грибы';
  if (o.kind === 'бактерия') return 'бактерии';
  return 'особая группа — лишайники (симбиоз гриба и водоросли, не относится ни к одному из четырёх перечисленных царств)';
}

