export function pickWordProblems(grade: ProblemGrade, count: number, category?: ProblemCategory): WordProblem[] {
  const pool = category ? WORD_PROBLEMS[grade].filter((p) => p.category === category) : WORD_PROBLEMS[grade];
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
