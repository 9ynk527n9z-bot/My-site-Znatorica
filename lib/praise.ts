// Похвала на экране результата — по факту, а не всем подряд.
//
// Раньше любой результат заканчивался словами «🎉 Молодец!» и значком
// «🏆 Магистр игры». Ребёнок, ответивший верно 1 раз из 9, получал то же самое,
// что и ответивший 9 из 9. Похвала, которая выдаётся всегда, перестаёт быть
// похвалой: она ничего не сообщает о результате и обесценивает настоящий успех.
//
// Шкала (в долях, чтобы работала и на 8, и на 10, и на 12 раундов):
//   всё верно  — «Магистр игры», единственный случай со значком
//   70–99 %    — «Молодец» (при 10 раундах это 7–9 верных)
//   40–69 %    — честно: получилось не всё, стоит потренироваться
//   меньше 40 % — поддержка без похвалы
//
// Заодно это чинит текст для соцсетей: делиться результатом «1 из 9» как
// достижением неловко, поэтому слабый результат уходит из текста совсем —
// остаётся просто рекомендация тренажёра.

export interface Praise {
  /** Заголовок экрана результата */
  title: string;
  /** Показывать ли значок «Магистр игры» — только за безошибочное прохождение */
  master: boolean;
  /** Уместно ли упоминать результат при отправке в чат */
  boast: boolean;
}

export function praiseFor(correct: number, total: number): Praise {
  const share = total > 0 ? correct / total : 0;

  if (total > 0 && correct === total) {
    return { title: '🏆 Идеально! Ни одной ошибки', master: true, boast: true };
  }
  if (share >= 0.7) {
    return { title: '🎉 Молодец!', master: false, boast: true };
  }
  return { title: '💪 Нужно постараться', master: false, boast: false };
}

/** Текст для отправки в чат: с результатом — только если им есть чем гордиться. */
export function shareTextFor(gameTitle: string, correct: number, total: number): string {
  const base = `Бесплатный тренажёр «${gameTitle}» для детей на Знаторике.`;
  return praiseFor(correct, total).boast
    ? `${base} Наш результат: ${correct} из ${total}.`
    : base;
}

/** То же для викторин на страницах тем. */
export function quizShareText(correct: number, total: number): string {
  const base = 'Бесплатная викторина для детей на Знаторике.';
  return praiseFor(correct, total).boast
    ? `${base} Наш результат: ${correct} из ${total}.`
    : base;
}
