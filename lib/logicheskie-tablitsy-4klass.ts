function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** Возвращает `count` случайных задач без повторов, с перемешанными вариантами ответа. */
export function pickLogicTableTasks4Klass(count: number): LogicTableTask4Klass[] {
  const shuffled = shuffle(LOGIC_TABLE_TASKS_4KLASS).slice(0, Math.min(count, LOGIC_TABLE_TASKS_4KLASS.length));
  return shuffled.map((task) => {
    const correctOption = task.options[task.correct];
    const shuffledOptions = shuffle(task.options);
    return {
      text: task.text,
      options: shuffledOptions,
      correct: shuffledOptions.indexOf(correctOption),
    };
  });
}
