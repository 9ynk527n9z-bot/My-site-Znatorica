// Порядок приоритета при равном количестве баллов — фиксированный, чтобы результат
// был детерминированным, а не зависел от порядка перебора объекта.
const TIEBREAK_ORDER: ParentStyle[] = ['opora', 'kapitan', 'drug', 'zhongler'];

export function computeResult(counts: Record<ParentStyle, number>): { winner: ParentStyle; percentByStyle: Record<ParentStyle, number> } {
  const total = QUESTIONS.length;
  const percentByStyle = {} as Record<ParentStyle, number>;
  for (const style of TIEBREAK_ORDER) {
    percentByStyle[style] = Math.round((100 * (counts[style] || 0)) / total);
  }
  let winner: ParentStyle = TIEBREAK_ORDER[0];
  let best = -1;
  for (const style of TIEBREAK_ORDER) {
    const c = counts[style] || 0;
    if (c > best) {
      best = c;
      winner = style;
    }
  }
  return { winner, percentByStyle };
}
